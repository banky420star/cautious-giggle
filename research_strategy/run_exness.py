"""Run the offline tournament and walk-forward on every cached Exness symbol.

Writes research_strategy/results/exness_tournament.json and summary.md.
Research only: nothing here touches MT5, the registry or the live server.
"""
import argparse
import json
from pathlib import Path

from research_strategy.exness_data import CACHE, COSTS, cost_per_side_bps, load_cache, resample
from research_strategy.tournament import signals, tournament, walk_forward

OUT = Path(__file__).resolve().parent / "results"


def pct(x):
    return f"{x * 100:+.2f}%"


def run(symbols, frames, folds, slippage_bps, stress):
    report = {"mode": "research_only", "folds": folds, "slippage_bps": slippage_bps,
              "cost_stress_multiplier": stress, "runs": []}
    for sym in symbols:
        base = load_cache(sym, "M5")
        cost = cost_per_side_bps(sym, slippage_bps)
        for frame, minutes in frames:
            rows = base if minutes == 5 else resample(base, minutes)
            sigs = signals(rows)
            t = tournament(rows, cost, sigs)
            wf = walk_forward(rows, cost, folds, sigs)
            wf_stress = walk_forward(rows, cost * stress, folds, sigs)
            report["runs"].append({
                "symbol": sym, "timeframe": frame, "bars": len(rows),
                "first": rows[0]["timestamp"], "last": rows[-1]["timestamp"],
                "cost_bps_per_side": cost, "tournament": t, "walk_forward": wf,
                "walk_forward_stressed_costs": wf_stress})
            top = t["strategies"][0]
            print(f"{sym} {frame}: bars={len(rows)} cost={cost}bps top={top['name']} "
                  f"val={pct(top['validation']['net_return'])} hold={pct(top['holdout']['net_return'])} "
                  f"WF={pct(wf['oos_net_return'])} B&H={pct(wf['buy_and_hold_oos_net_return'])}",
                  flush=True)
    return report


def summary(report):
    lines = [
        "# Exness cache tournament results",
        "",
        "Research only. Generated by `python -m research_strategy.run_exness`.",
        f"Costs per side come from `data/zero_costs.json` (half commission + half standard spread"
        f" + {report['slippage_bps']} bps slippage). Walk-forward uses {report['folds']} expanding folds;"
        " each fold trades only the strategy that did best before it, or stays flat if none made money.",
        "",
        "| Symbol | TF | Bars | Cost/side | Top on validation | Validation | Holdout | Walk-forward OOS | "
        f"WF at {report['cost_stress_multiplier']}x cost | Buy & hold (same windows) | WF folds > 0 |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in report["runs"]:
        top = r["tournament"]["strategies"][0]
        wf, ws = r["walk_forward"], r["walk_forward_stressed_costs"]
        lines.append(
            f"| {r['symbol']} | {r['timeframe']} | {r['bars']:,} | {r['cost_bps_per_side']} bps | "
            f"{top['name']} | {pct(top['validation']['net_return'])} | {pct(top['holdout']['net_return'])} | "
            f"{pct(wf['oos_net_return'])} | {pct(ws['oos_net_return'])} | "
            f"{pct(wf['buy_and_hold_oos_net_return'])} | {wf['folds_positive']}/{len(wf['folds'])} |")
    lines += [
        "",
        "Picks by fold (walk-forward):",
        "",
    ]
    for r in report["runs"]:
        picks = ", ".join(f["pick"] for f in r["walk_forward"]["folds"])
        lines.append(f"- {r['symbol']} {r['timeframe']}: {picks}")
    lines += [
        "",
        "## How to read this",
        "",
        "- Returns are unlevered signed exposure (1x notional), next-open fills, no stops or sizing.",
        "- \"Holdout\" was never used for ranking. A strategy that tops validation but loses on holdout"
        " did not generalise.",
        "- Walk-forward is the fairer test: it simulates re-picking the best rule as time passes.",
        "- The cache spans roughly one year of M5 bars per symbol. One year, one broker feed and"
        " simplified rules are not enough evidence to put any of these in front of real money.",
        "- Gaps (weekends, daily breaks) are kept as-is; an M5 bar after a gap fills at that bar's open.",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    costs = json.loads(COSTS.read_text())
    available = [s for s in costs if (CACHE / f"{s}_M5.npy").is_file()]
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--symbols", nargs="*", default=available)
    p.add_argument("--folds", type=int, default=5)
    p.add_argument("--slippage-bps", type=float, default=0.5)
    p.add_argument("--stress", type=float, default=3.0)
    p.add_argument("--no-m5", action="store_true", help="only run the H1 resample")
    a = p.parse_args()
    frames = ([] if a.no_m5 else [("M5", 5)]) + [("H1", 60)]
    rep = run(a.symbols, frames, a.folds, a.slippage_bps, a.stress)
    OUT.mkdir(exist_ok=True)
    (OUT / "exness_tournament.json").write_text(json.dumps(rep, indent=2, allow_nan=False))
    (OUT / "summary.md").write_text(summary(rep))
    print(f"wrote {OUT / 'summary.md'}")
